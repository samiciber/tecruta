  await login(rt.admin.email)
  await page.getByRole('navigation', { name: 'Secciones del panel' }).waitFor()
  for (const [device, viewport] of [['tablet', { width: 834, height: 1112 }], ['movil', { width: 390, height: 844 }]]) {
    await page.setViewportSize(viewport)
    for (const theme of ['claro', 'oscuro']) {
      const dark = await page.evaluate(() => document.documentElement.classList.contains('dark'))
      if (dark !== (theme === 'oscuro')) await page.getByRole('button', { name: /Cambiar a modo/ }).click()
      await capture('dashboard-' + device + '-' + theme)
    }
  }
  check('Panel adaptable a escritorio/tablet/móvil y temas claro/oscuro')
  await page.setViewportSize({ width: 1440, height: 1000 })
  // Different origins must not inherit the panel's session.
  await page.goto(rt.shop + '/iniciar-sesion')
