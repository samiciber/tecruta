  await login(rt.admin.email)
  await page.getByRole('navigation', { name: 'Secciones del panel' }).waitFor()
  await page.goto(rt.panel + '/ajustes')
  await page.getByLabel('Texto', { exact: true }).fill('Promoción sintética de revisión')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar', exact: true }).waitFor({ state: 'visible' })
  await page.waitForFunction(() => document.querySelector('form button[type=submit]')?.disabled)
  await page.reload()
  assert.equal(await page.getByLabel('Texto', { exact: true }).inputValue(), 'Promoción sintética de revisión')
  await page.goto(rt.panel + '/home-layout')
  await page.getByRole('button', { name: 'Previsualizar borrador', exact: true }).click()
  await page.getByRole('heading', { name: 'Previsualización del borrador (sin guardar)', exact: true }).waitFor()
  assert.equal(await page.locator('[inert]').count(), 1)
  await page.goto(rt.panel)
  await page.getByRole('navigation', { name: 'Secciones del panel' }).waitFor()
  check('Ajuste administrativo persiste y previsualización del Home conserva el render sin compras')
  assert.equal(await page.locator('footer').count(), 0)
  await capture('dashboard-escritorio-claro')
  await page.goto(rt.panel + '/admin/home-layout?revision=1')
  await page.waitForURL('**/home-layout?revision=1')
  await page.reload()
  await page.getByRole('navigation', { name: 'Secciones del panel' }).waitFor()
  check('Compatibilidad /admin y recarga directa conservan ruta y sesión')
  await page.goto(rt.panel + '/usuarios')
  await page.getByRole('heading', { name: 'Usuarios y permisos', exact: true }).waitFor()
  await page.getByLabel('Nombre', { exact: true }).fill('Trabajador')
  await page.getByLabel('Apellido', { exact: true }).fill('Sintético')
  await page.getByLabel('Correo del trabajador', { exact: true }).fill('qa-invited@example.test')
  await page.getByRole('button', { name: 'Crear cuenta y enviar activación', exact: true }).click()
  await page.getByText('qa-invited@example.test', { exact: true }).waitFor()
  await page.reload()
  await page.getByText('qa-invited@example.test', { exact: true }).waitFor()
  await capture('usuarios-escritorio-claro')
  const code = rt.outbox.find(message => message.to === 'qa-invited@example.test').code
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await page.getByRole('link', { name: 'Activar cuenta o recuperar contraseña', exact: true }).click()
  await page.getByRole('textbox', { name: 'Correo electrónico', exact: true }).fill('qa-invited@example.test')
  await page.getByRole('button', { name: 'Ya tengo un código de activación o recuperación', exact: true }).click()
  await page.getByRole('textbox', { name: 'Código de verificación', exact: true }).fill(code)
  await page.getByLabel('Nueva contraseña', { exact: true }).fill('Synthetic-new-worker-42')
  await page.getByLabel('Confirmar nueva contraseña', { exact: true }).fill('Synthetic-new-worker-42')
  await page.getByRole('button', { name: 'Restablecer contraseña', exact: true }).click()
  await page.getByRole('heading', { name: 'Contraseña actualizada', exact: true }).waitFor()
  await login('qa-invited@example.test', 'Synthetic-new-worker-42')
  await page.getByRole('heading', { name: 'Nueva venta', exact: true }).waitFor()
  check('Invitación, persistencia, activación privada y acceso real del nuevo cajero')
  await page.goto(rt.panel + '/inventario')
  await page.getByRole('heading', { name: 'Kardex', exact: true }).waitFor()
  assert.equal(await page.getByRole('link', { name: 'Usuarios y permisos', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await login(rt.warehouse.email)
  await page.waitForURL('**/inventario')
  await page.getByRole('heading', { name: 'Kardex', exact: true }).waitFor()
