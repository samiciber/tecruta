  await page.evaluate(token => { localStorage.removeItem('tecruta:token'); sessionStorage.setItem('tecruta:token', JSON.stringify(token)) }, expired)
  await page.goto(rt.panel + '/usuarios')
  await page.waitForURL('**/iniciar-sesion?volver=*')
  await page.getByRole('heading', { name: 'Panel TecRuta', exact: true }).waitFor()
  check('Ruta POS anterior redirige y una sesión expirada vuelve al login del panel')
  assert.deepEqual(errors, [])
  writeFileSync(join(evidence, 'resultados.json'), JSON.stringify({ checks, captures, errors }, null, 2))
