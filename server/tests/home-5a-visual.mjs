import http from 'node:http'
import { createServer } from 'vite'
import { resolveHome } from '../src/lib/homeResolver.js'
import { homeLayoutSchema } from '../src/lib/homeSchemas.js'
import { homeBannersSchema } from '../src/lib/navSchemas.js'
import { serializeProduct } from '../src/lib/serializers.js'

const origin = 'http://127.0.0.1:4405'
const products = Array.from({ length: 8 }, (_, i) => ({
  id: `visual-${i}`, slug: `visual-${i}`, name: ['Audífonos inalámbricos de prueba', 'Cargador USB-C de prueba', 'Teclado compacto de prueba', 'Parlante portátil de prueba'][i % 4],
  brand: 'Marca sintética', price: 99.9 + i * 20, compareAtPrice: i % 2 ? null : 149.9 + i * 20,
  stock: i === 1 ? 0 : i === 2 ? 3 : 12, featured: true, bestSeller: true,
  image: `${origin}/fixtures/product-${i}.svg`, images: [], category: { slug: 'accesorios' }, brandRef: null,
}))
const categories = [{ id: 'visual-cat', slug: 'accesorios', name: 'Accesorios', parentId: null, visible: true, legacy: false, image: `${origin}/fixtures/product-0.svg`, _count: { products: 8 } }]
const makeBanner = (id, title, placement = 'hero', width = 'full') => ({
  id, title, eyebrow: 'Contenido sintético · revisión 5a',
  description: 'Tecnología para acompañarte cada día. Explora nuestra selección de accesorios de prueba.',
  buttons: [{ label: 'Explorar catálogo', href: '/catalogo', style: 'primary' }, { label: 'Conocer más', href: '/ayuda', style: 'secondary' }],
  imageDesktop: `${origin}/fixtures/banner.svg`, imageAlt: 'Ilustración local de prueba',
  placement, width, slot: 'visual', active: true, position: 'middle-left', textAlign: 'left', overlay: 25,
})
const settings = {
  homeBanners: homeBannersSchema.parse([
    makeBanner('hero-a', 'Tecnología que te acompaña'), makeBanner('hero-b', 'Accesorios para cada momento'),
    makeBanner('inline-full', 'Todo para tu espacio de trabajo', 'inline'),
    makeBanner('inline-half-a', 'Conecta con tus favoritos', 'inline', 'half'),
    makeBanner('inline-half-b', 'Más energía para tu día', 'inline', 'half'),
  ]),
  heroCarousel: { autoplay: false, intervalSeconds: 6 },
  homeCircles: { title: 'Compra por categoría', onlyWithProducts: true },
}
const layout = homeLayoutSchema.parse({ sections: [
  { id: 'hero', type: 'hero' }, { id: 'guest', type: 'guestStrip' }, { id: 'circles', type: 'circles' },
  { id: 'with-panel', type: 'products', title: 'Destacados de prueba', limit: 8,
    sources: [{ id: 'featured', label: 'Destacados', kind: 'featured', href: '/catalogo' }, { id: 'best', label: 'Más vendidos', kind: 'bestSeller', href: '/catalogo' }],
    panel: { title: 'Equipa tu día', description: 'Panel lateral configurado. Datos sintéticos resueltos por el backend real.', label: 'Ver accesorios', href: '/catalogo' } },
  { id: 'inline', type: 'inlineBanners', slot: 'visual' },
  { id: 'without-panel', type: 'products', title: 'Selección sin panel', sources: [{ id: 'featured2', label: 'Accesorios', kind: 'featured', href: '/catalogo' }] },
] })
const db = {
  product: { fields: { price: {} }, findMany: async ({ take }) => products.slice(0, take) },
  category: { findMany: async () => categories },
}
const requests = []
const api = http.createServer(async (req, res) => {
  res.setHeader('Access-Control-Allow-Origin', 'http://127.0.0.1:5175')
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization')
  if (req.method === 'OPTIONS') { res.writeHead(204); res.end(); return }
  const path = new URL(req.url, origin).pathname
  requests.push(path)
  if (path.startsWith('/fixtures/')) {
    res.setHeader('Content-Type', 'image/svg+xml')
    const isProduct = path.includes('product')
    res.end(`<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="600" viewBox="0 0 1600 600"><rect width="1600" height="600" fill="${isProduct ? '#dbeafe' : '#12324b'}"/><circle cx="1200" cy="250" r="190" fill="#2087a3"/><rect x="${isProduct ? 650 : 1050}" y="125" width="250" height="350" rx="35" fill="#16394f" stroke="#8ae0e8" stroke-width="12"/><circle cx="${isProduct ? 775 : 1175}" cy="420" r="15" fill="#8ae0e8"/></svg>`)
    return
  }
  res.setHeader('Content-Type', 'application/json')
  try {
    // The public payload is always generated by the real schema/resolver.
    if (path === '/api/home') return res.end(JSON.stringify(await resolveHome({ db, layout, settings })))
    const responses = {
      '/api/site-settings': settings, '/api/categories': categories,
      '/api/categories/tree': categories.map(c => ({ ...c, children: [], productCount: 8 })),
      '/api/brands': { featured: [], all: [] }, '/api/popular-searches': [], '/api/stores': [],
      '/api/nav': { menus: { acuerdos: [], soporte: [], descubre: [], mas: [], quick: [] }, seasonalPromo: null }, '/api/products': products.map(serializeProduct),
      '/__qa/requests': requests,
    }
    if (path in responses) return res.end(JSON.stringify(responses[path]))
    res.writeHead(404); res.end(JSON.stringify({ error: 'Ruta no incluida en el fixture local' }))
  } catch (error) { res.writeHead(500); res.end(JSON.stringify({ error: error.message })) }
})
await new Promise(resolve => api.listen(4405, '127.0.0.1', resolve))
const vite = await createServer({
  envFile: false,
  define: { 'import.meta.env.VITE_API_URL': JSON.stringify(origin) },
  server: { host: '127.0.0.1', port: 5175, strictPort: true,
    headers: { 'Content-Security-Policy': "default-src 'self' data: blob:; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: http://127.0.0.1:4405; connect-src 'self' ws://127.0.0.1:5175 http://127.0.0.1:4405; font-src 'self' data:; frame-src 'none'" } },
})
await vite.listen()
console.log('Visual QA: http://127.0.0.1:5175; synthetic API via real resolveHome on 4405; envFile=false')
const stop = async () => { await vite.close(); api.close(); process.exit(0) }
process.on('SIGINT', stop)
process.on('SIGTERM', stop)
